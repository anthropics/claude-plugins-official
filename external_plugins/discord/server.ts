type PendingEntry = {
  senderId: string
  chatId: string // DM channel ID — where to send the approval confirm
  createdAt: number
  expiresAt: number
  replies: number
}

type GroupPolicy = {
  requireMention: boolean
  allowFrom: string[]
  /**
   * Sticky mention window, in minutes. 0 or absent = off (every message needs a
   * mention, the default). When > 0: a mention or a reply to the bot opens a window
   * of this many minutes in the channel, and messages in the window are delivered
   * without a mention. Each mention or reply restarts the window.
   */
  stickyMinutes?: number
  /** Deliver message edits (see handleEdit). Default false. */
  edits?: boolean
  /**
   * Catch-up context, in messages. 0 or absent = off. When > 0: a message delivered
   * because of a mention is preceded by up to this many earlier messages from the
   * same channel or thread, so the assistant sees what the mention refers to.
   */
  catchUpMaxMessages?: number
  /** How far back catch-up looks, in minutes. Default 15. */
  catchUpMaxMinutes?: number
}

type Access = {
  dmPolicy: 'pairing' | 'allowlist' | 'disabled'
  allowFrom: string[]
  /** Keyed on channel ID (snowflake), not guild ID. One entry per guild channel. */
  groups: Record<string, GroupPolicy>
  /**
   * Server-wide opt-in, keyed on guild ID. Applies to every channel (and thread)
   * in that server that has no entry in `groups`. A `groups` entry always wins.
   */
  guilds?: Record<string, GroupPolicy>
  pending: Record<string, PendingEntry>
  mentionPatterns?: string[]
  // delivery/UX config — optional, defaults live in the reply handler
  /** Emoji to react with on receipt. Empty string disables. Unicode char or custom emoji ID. */
  ackReaction?: string
  /** Which chunks get Discord's reply reference when reply_to is passed. Default: 'first'. 'off' = never thread. */
  replyToMode?: 'off' | 'first' | 'all'
  /** Max chars per outbound message before splitting. Default: 2000 (Discord's hard cap). */
  textChunkLimit?: number
  /** Split on paragraph boundaries instead of hard char count. */
  chunkMode?: 'length' | 'newline'
}

function defaultAccess(): Access {
  return {
    dmPolicy: 'pairing',
    allowFrom: [],
    groups: {},
    pending: {},
  }
}


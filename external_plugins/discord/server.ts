// reply's files param takes any path. .env is ~60 bytes and ships as an
// upload. Claude can already Read+paste file contents, so this isn't a new
// exfil channel for arbitrary paths — but the server's own state is the one
// thing Claude has no reason to ever send.
function assertSendable(f: string): void {
  let real, stateReal: string
  try {
    real = realpathSync(f)
    stateReal = realpathSync(STATE_DIR)
  } catch { return } // statSync will fail properly; or STATE_DIR absent → nothing to leak
  const inbox = join(stateReal, 'inbox')
  if (real.startsWith(stateReal + sep) && !real.startsWith(inbox + sep)) {
    throw new Error(`refusing to send channel state: ${f}`)
  }
}

function readAccessFile(): Access {
  try {
    const raw = readFileSync(ACCESS_FILE, 'utf8')
    const parsed = JSON.parse(raw) as Partial<Access>
    return {
      dmPolicy: parsed.dmPolicy ?? 'pairing',
      allowFrom: parsed.allowFrom ?? [],
      groups: parsed.groups ?? {},
      guilds: parsed.guilds,
      pending: parsed.pending ?? {},
      mentionPatterns: parsed.mentionPatterns,
      ackReaction: parsed.ackReaction,
      replyToMode: parsed.replyToMode,
      textChunkLimit: parsed.textChunkLimit,
      chunkMode: parsed.chunkMode,
    }
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code === 'ENOENT') return defaultAccess()
    try { renameSync(ACCESS_FILE, `${ACCESS_FILE}.corrupt-${Date.now()}`) } catch {}
    process.stderr.write(`discord: access.json is corrupt, moved aside. Starting fresh.\n`)
    return defaultAccess()
  }
}

// In static mode, access is snapshotted at boot and never re-read or written.
// Pairing requires runtime mutation, so it's downgraded to allowlist with a
// startup warning — handing out codes that never get approved would be worse.
const BOOT_ACCESS: Access | null = STATIC
  ? (() => {
      const a = readAccessFile()
      if (a.dmPolicy === 'pairing') {
        process.stderr.write(
          'discord channel: static mode — dmPolicy "pairing" downgraded to "allowlist"\n',
        )
        a.dmPolicy = 'allowlist'
      }
      a.pending = {}
      return a
    })()
  : null

function loadAccess(): Access {
  return BOOT_ACCESS ?? readAccessFile()
}

function saveAccess(a: Access): void {
  if (STATIC) return
  mkdirSync(STATE_DIR, { recursive: true, mode: 0o700 })
  const tmp = ACCESS_FILE + '.tmp'
  writeFileSync(tmp, JSON.stringify(a, null, 2) + '\n', { mode: 0o600 })
  renameSync(tmp, ACCESS_FILE)
}

function pruneExpired(a: Access): boolean {
  const now = Date.now()
  let changed = false
  for (const [code, p] of Object.entries(a.pending)) {
    if (p.expiresAt < now) {
      delete a.pending[code]
      changed = true
    }
  }
  return changed
}

type GateResult =
  /** sticky: delivered only because a sticky window was open (no mention). */
  | { action: 'deliver'; access: Access; sticky?: boolean; catchUp?: CatchUp }
  | { action: 'drop' }
  | { action: 'pair'; code: string; isResend: boolean }

// Track message IDs we recently sent, so reply-to-bot in guild channels
// counts as a mention without needing fetchReference().
const recentSentIds = new Set<string>()
const RECENT_SENT_CAP = 200

const dmChannelUsers = new Map<string, string>()

function noteSent(id: string): void {
  recentSentIds.add(id)
  if (recentSentIds.size > RECENT_SENT_CAP) {
    // Sets iterate in insertion order — this drops the oldest.
    const first = recentSentIds.values().next().value
    if (first) recentSentIds.delete(first)
  }
}

// Sticky mention windows: channel or thread ID -> when the window closes, and the
// window length to restart it with. Keyed on where the conversation happens
// (msg.channelId), not the parent channel used for the policy lookup, so a mention
// in one thread doesn't open the parent channel or sibling threads. In-memory only:
// a restart closes all windows (fails safe: a mention is required again).
const stickyWindows = new Map<string, { until: number; minutes: number }>()
const STICKY_MAX_MINUTES = 24 * 60

// The bot replying in a channel keeps an already-open window alive, so an active
// conversation doesn't close mid-thread. Never opens a window: only a mention does.
// Bot messages are never delivered back to the model, so this costs nothing itself.
function extendStickyWindow(chatId: string): void {
  const w = stickyWindows.get(chatId)
  if (w && Date.now() < w.until) w.until = Date.now() + w.minutes * 60_000
}

// access.json is hand-editable, so don't trust the type or range.
function stickyMinutesOf(policy: GroupPolicy): number {
  const n = Math.floor(Number(policy.stickyMinutes ?? 0))
  return Number.isFinite(n) ? Math.min(Math.max(n, 0), STICKY_MAX_MINUTES) : 0
}

// Catch-up context: earlier messages delivered ahead of a mention. Only the
// gate's own sender filter applies (allowFrom), so catch-up can't surface
// anyone the gate would have dropped.
type CatchUp = { messages: number; minutes: number; allowFrom: string[] }
const CATCH_UP_MAX_MESSAGES = 50
const CATCH_UP_DEFAULT_MINUTES = 15

// Newest delivered message per channel or thread, so catch-up skips what the
// assistant already saw. In-memory: after a restart, catch-up may repeat a few.
const lastDeliveredAt = new Map<string, number>()

function catchUpOf(policy: GroupPolicy): CatchUp | undefined {
  const n = Math.floor(Number(policy.catchUpMaxMessages ?? 0))
  if (!Number.isFinite(n) || n <= 0) return undefined
  const m = Math.floor(Number(policy.catchUpMaxMinutes ?? CATCH_UP_DEFAULT_MINUTES))
  return {
    messages: Math.min(n, CATCH_UP_MAX_MESSAGES),
    minutes: Number.isFinite(m) ? Math.min(Math.max(m, 1), STICKY_MAX_MINUTES) : CATCH_UP_DEFAULT_MINUTES,
    allowFrom: policy.allowFrom ?? [],
  }
}

// channelId is the parent channel for threads. Own-property checks, since the
// IDs come from Discord and the maps from a hand-editable file.
function policyFor(access: Access, channelId: string, guildId: string | null): GroupPolicy | undefined {
  if (Object.hasOwn(access.groups, channelId)) return access.groups[channelId]
  if (guildId && access.guilds && Object.hasOwn(access.guilds, guildId)) return access.guilds[guildId]
  return undefined
}

async function gate(msg: Message): Promise<GateResult> {
  const access = loadAccess()
  const pruned = pruneExpired(access)
  if (pruned) saveAccess(access)

  if (access.dmPolicy === 'disabled') return { action: 'drop' }

  const senderId = msg.author.id
  const isDM = msg.channel.type === ChannelType.DM

  if (isDM) {
    if (access.allowFrom.includes(senderId)) return { action: 'deliver', access }
    if (access.dmPolicy === 'allowlist') return { action: 'drop' }

    // pairing mode — check for existing non-expired code for this sender
    for (const [code, p] of Object.entries(access.pending)) {
      if (p.senderId === senderId) {
        // Reply twice max (initial + one reminder), then go silent.
        if ((p.replies ?? 1) >= 2) return { action: 'drop' }
        p.replies = (p.replies ?? 1) + 1
        saveAccess(access)
        return { action: 'pair', code, isResend: true }
      }
    }
    // Cap pending at 3. Extra attempts are silently dropped.
    if (Object.keys(access.pending).length >= 3) return { action: 'drop' }

    const code = randomBytes(3).toString('hex') // 6 hex chars
    const now = Date.now()
    access.pending[code] = {
      senderId,
      chatId: msg.channelId, // DM channel ID — used later to confirm approval
      createdAt: now,
      expiresAt: now + 60 * 60 * 1000, // 1h
      replies: 1,
    }
    saveAccess(access)
    return { action: 'pair', code, isResend: false }
  }

  // Per-channel entries (groups) win; a server-wide entry (guilds) covers
  // every other channel in that server. Threads inherit their parent
  // channel's opt-in; the reply still goes to msg.channelId (the thread),
  // this is only the gate lookup.
  const channelId = msg.channel.isThread()
    ? msg.channel.parentId ?? msg.channelId
    : msg.channelId
  const policy = policyFor(access, channelId, msg.guildId)
  if (!policy) return { action: 'drop' }
  const groupAllowFrom = policy.allowFrom ?? []
  const requireMention = policy.requireMention ?? true
  if (groupAllowFrom.length > 0 && !groupAllowFrom.includes(senderId)) {
    return { action: 'drop' }
  }
  if (!requireMention) return { action: 'deliver', access }

  const sticky = stickyMinutesOf(policy)
  if (await isMentioned(msg, access.mentionPatterns)) {
    // A mention or a reply to the bot (re)opens the sticky window.
    if (sticky > 0) {
      stickyWindows.set(msg.channelId, { until: Date.now() + sticky * 60_000, minutes: sticky })
    }
    return { action: 'deliver', access, catchUp: catchUpOf(policy) }
  }
  // No mention: deliver only while a sticky window is open here.
  const w = stickyWindows.get(msg.channelId)
  if (w) {
    if (sticky > 0 && Date.now() < w.until) return { action: 'deliver', access, sticky: true }
    stickyWindows.delete(msg.channelId) // expired, or sticky was turned off
  }
  return { action: 'drop' }
}

async function isMentioned(msg: Message, extraPatterns?: string[]): Promise<boolean> {
  if (client.user && msg.mentions.has(client.user)) return true

  // Reply to one of our messages counts as an implicit mention.
  const refId = msg.reference?.messageId
  if (refId) {
    if (recentSentIds.has(refId)) return true
    // Fallback: fetch the referenced message and check authorship.
    // Can fail if the message was deleted or we lack history perms.
    try {
      const ref = await msg.fetchReference()
      if (ref.author.id === client.user?.id) return true
    } catch {}
  }

  const text = msg.content
  for (const pat of extraPatterns ?? []) {
    try {
      if (new RegExp(pat, 'i').test(text)) return true
    } catch {}
  }
  return false
}

// The /discord:access skill drops a file at approved/<senderId> when it pairs
// someone. Poll for it, send confirmation, clean up. Discord DMs have a
// distinct channel ID ≠ user ID, so we need the chatId stashed in the
// pending entry — but by the time we see the approval file, pending has
// already been cleared. Instead: the approval file's *contents* carry
// the DM channel ID. (The skill writes it.)

function checkApprovals(): void {
  let files: string[]
  try {
    files = readdirSync(APPROVED_DIR)
  } catch {
    return
  }
  if (files.length === 0) return

  for (const senderId of files) {
    const file = join(APPROVED_DIR, senderId)
    let dmChannelId: string
    try {
      dmChannelId = readFileSync(file, 'utf8').trim()
    } catch {
      rmSync(file, { force: true })
      continue
    }
    if (!dmChannelId) {
      // No channel ID — can't send. Drop the marker.
      rmSync(file, { force: true })
      continue
    }

    void (async () => {
      try {
        const ch = await fetchTextChannel(dmChannelId)
        if ('send' in ch) {
          await ch.send("Paired! Say hi to Claude.")
        }
        rmSync(file, { force: true })
      } catch (err) {
        process.stderr.write(`discord channel: failed to send approval confirm: ${err}\n`)
        // Remove anyway — don't loop on a broken send.
        rmSync(file, { force: true })
      }
    })()
  }
}

